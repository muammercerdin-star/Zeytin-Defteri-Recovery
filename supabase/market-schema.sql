-- Bu dosyayı Supabase SQL Editor'de bir kez çalıştır.
-- Ham kullanıcı UID'si tutulmaz. Edge Function UID'yi HMAC/SHA-256 ile producer_hash'e çevirir.

create table if not exists public.zd_market_consents (
    producer_hash text primary key,
    enabled boolean not null default false,
    policy_version integer not null default 1,
    updated_at timestamptz not null default now(),
    constraint zd_market_consents_hash_len check (char_length(producer_hash) = 64)
);

create table if not exists public.zd_market_contributions (
    id bigint generated by default as identity primary key,
    producer_hash text not null references public.zd_market_consents(producer_hash) on delete cascade,
    season_year integer not null,
    source_key text not null,
    record_date date not null,
    region_id text not null,
    region_name text not null,
    district text not null,
    province text not null,
    grade text not null,
    kg numeric(16,3) not null,
    price_per_kg numeric(16,2) not null,
    updated_at timestamptz not null default now(),
    constraint zd_market_contrib_year check (season_year between 2000 and 2100),
    constraint zd_market_contrib_grade check (grade in ('DOUBLE','1','2','3','4','YAGLIK')),
    constraint zd_market_contrib_kg check (kg > 0 and kg <= 1000000000),
    constraint zd_market_contrib_price check (price_per_kg > 0 and price_per_kg <= 10000000),
    constraint zd_market_contrib_source unique (producer_hash, season_year, source_key, grade)
);

create index if not exists zd_market_contrib_region_idx
    on public.zd_market_contributions(season_year, region_id, grade, record_date desc);

create index if not exists zd_market_contrib_province_idx
    on public.zd_market_contributions(season_year, province, grade, record_date desc);

create index if not exists zd_market_contrib_producer_idx
    on public.zd_market_contributions(producer_hash, season_year);

-- İstemcilerin ham tablolara doğrudan erişmesini kapat.
alter table public.zd_market_consents enable row level security;
alter table public.zd_market_contributions enable row level security;

revoke all on table public.zd_market_consents from anon, authenticated;
revoke all on table public.zd_market_contributions from anon, authenticated;

-- Edge Function service role ile çalışır.
grant select, insert, update, delete on table public.zd_market_consents to service_role;
grant select, insert, update, delete on table public.zd_market_contributions to service_role;
grant usage, select on all sequences in schema public to service_role;

-- Yalnız 5+ farklı üreticiye ulaşan bölgeler istemciye listelenir.
create or replace function public.zd_market_public_regions(p_season_year integer)
returns table(
    id text,
    name text,
    district text,
    province text,
    producer_count bigint
)
language sql
stable
security definer
set search_path = ''
as $$
    select
        c.region_id as id,
        max(c.region_name) as name,
        max(c.district) as district,
        max(c.province) as province,
        count(distinct c.producer_hash) as producer_count
    from public.zd_market_contributions c
    join public.zd_market_consents s
      on s.producer_hash = c.producer_hash
     and s.enabled = true
     and s.policy_version = 1
    where c.season_year = p_season_year
    group by c.region_id
    having count(distinct c.producer_hash) >= 5
    order by max(c.province), max(c.district);
$$;

revoke all on function public.zd_market_public_regions(integer) from public, anon, authenticated;
grant execute on function public.zd_market_public_regions(integer) to service_role;

comment on table public.zd_market_contributions is
